//! Golden structs for Anthropic Messages API spec compliance.
//!
//! Derived from: https://docs.anthropic.com/en/api/messages
//! Streaming: https://docs.anthropic.com/en/api/messages-streaming
//! Target: latest API version (2025)

use serde::Deserialize;

// ---------------------------------------------------------------------------
// Non-streaming response
// ---------------------------------------------------------------------------

/// The Messages response object.
/// Spec: https://docs.anthropic.com/en/api/messages
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SpecMessagesResponse {
    /// Unique message identifier (format: `msg_...`).
    pub id: String,
    /// Object type, always `"message"`.
    #[serde(rename = "type")]
    pub msg_type: String,
    /// Conversational role, always `"assistant"`.
    pub role: String,
    /// Array of content blocks generated by the model.
    pub content: Vec<SpecContentBlock>,
    /// The model that handled the request.
    pub model: String,
    /// Reason the model stopped: `"end_turn"`, `"max_tokens"`, `"stop_sequence"`, `"tool_use"`.
    pub stop_reason: Option<String>,
    /// Which custom stop sequence was matched (if any).
    pub stop_sequence: Option<String>,
    /// Billing and rate-limit usage.
    pub usage: SpecAnthropicUsage,
}

/// A content block in the response.
#[derive(Debug, Deserialize)]
#[serde(tag = "type")]
pub enum SpecContentBlock {
    /// Text content block.
    #[serde(rename = "text")]
    Text {
        text: String,
        #[serde(default)]
        citations: Option<serde_json::Value>,
    },
    /// Tool use content block.
    #[serde(rename = "tool_use")]
    ToolUse {
        id: String,
        name: String,
        input: serde_json::Value,
    },
}

/// Usage statistics.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SpecAnthropicUsage {
    pub input_tokens: u64,
    pub output_tokens: u64,
    #[serde(default)]
    pub cache_creation_input_tokens: Option<u64>,
    #[serde(default)]
    pub cache_read_input_tokens: Option<u64>,
}

// ---------------------------------------------------------------------------
// Streaming events
// ---------------------------------------------------------------------------

// Streaming event wrapper — each SSE event has an event type and JSON data.
// We parse events individually, not as a single struct.

/// message_start event data
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SpecMessageStartEvent {
    #[serde(rename = "type")]
    pub event_type: String,
    pub message: SpecMessageStartPayload,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SpecMessageStartPayload {
    pub id: String,
    #[serde(rename = "type")]
    pub msg_type: String,
    pub role: String,
    pub model: String,
    pub content: Vec<serde_json::Value>,
    pub stop_reason: Option<String>,
    pub stop_sequence: Option<String>,
    pub usage: SpecAnthropicUsage,
}

/// content_block_start event data
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SpecContentBlockStartEvent {
    #[serde(rename = "type")]
    pub event_type: String,
    pub index: u64,
    pub content_block: SpecContentBlockStart,
}

#[derive(Debug, Deserialize)]
#[serde(tag = "type")]
pub enum SpecContentBlockStart {
    #[serde(rename = "text")]
    Text { text: String },
    #[serde(rename = "tool_use")]
    ToolUse {
        id: String,
        name: String,
        input: serde_json::Value,
    },
}

/// content_block_delta event data
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SpecContentBlockDeltaEvent {
    #[serde(rename = "type")]
    pub event_type: String,
    pub index: u64,
    pub delta: SpecDelta,
}

#[derive(Debug, Deserialize)]
#[serde(tag = "type")]
pub enum SpecDelta {
    #[serde(rename = "text_delta")]
    TextDelta { text: String },
    #[serde(rename = "input_json_delta")]
    InputJsonDelta { partial_json: String },
}

/// content_block_stop event data
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SpecContentBlockStopEvent {
    #[serde(rename = "type")]
    pub event_type: String,
    pub index: u64,
}

